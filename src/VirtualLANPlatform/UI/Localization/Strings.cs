namespace VirtualLANPlatform.UI.Localization;

/// <summary>
/// The string table, one entry per user-visible piece of text.
///
/// <para>
/// Plain dictionaries rather than .resx: the app needs to swap language live, and satellite
/// resource assemblies resolve per-thread-culture at first read and then cache, which is
/// the opposite of what a live toggle needs.
/// </para>
/// <para>
/// English is deliberately not a word-for-word rendering of the Persian. The Persian copy
/// is colloquial on purpose, so the English is written to land the same way rather than to
/// match it literally.
/// </para>
/// </summary>
internal static class Strings
{
    public static string Get(AppLanguage language, string key)
    {
        var table = language == AppLanguage.English ? En : Fa;
        if (table.TryGetValue(key, out string? value)) return value;
        // Fall back to Persian before giving up, so a key that only exists in one table
        // still shows real text instead of a raw identifier.
        if (Fa.TryGetValue(key, out string? fallback)) return fallback;
        return key;
    }

